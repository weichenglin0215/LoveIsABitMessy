// ============================================================
// 配對推薦函式（給結果頁用）
// ============================================================
//
// 規則：
//   - best（最契合）：取該型的同型配對 + 從 PAIRING_MATRIX 找標記為 chemistry 高的
//   - complement（最互補）：與本型差 2-3 軸的型
//   - danger（最危險）：與本型 outcome tragic 比例最高的對撞型
//
// 簡化版：直接從 TYPE_MAPPING_V2_PUBLIC[type].pairing 讀取手工指定值
//        該欄位已在 types.js 中為每型寫好

window.lpasGetPairingRecommend = function (typeName) {
    if (!window.TYPE_MAPPING_V2_PUBLIC) return null;
    const t = window.TYPE_MAPPING_V2_PUBLIC[typeName];
    if (!t) return null;
    return t.pairing;  // { best: [...], complement: [...], danger: [...] }
};


/**
 * 取得兩型互動描述（給小說生成用）
 * @param {string} a 第一型名（中文）
 * @param {string} b 第二型名（中文）
 */
window.lpasGetPairingDetail = function (a, b) {
    if (!window.PAIRING_MATRIX) return null;
    return window.PAIRING_MATRIX[`${a}×${b}`]
        || window.PAIRING_MATRIX[`${b}×${a}`]
        || null;
};
